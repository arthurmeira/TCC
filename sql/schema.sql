BEGIN;

DO $$
BEGIN
    IF current_database() <> 'tcc_sql_optimizer_logs' THEN
        RAISE EXCEPTION
            'Execute este script no banco tcc_sql_optimizer_logs. Banco atual: %',
            current_database();
    END IF;
END;
$$;

CREATE TABLE public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    cidade VARCHAR(100) NOT NULL,
    estado VARCHAR(2) NOT NULL,
    data_cadastro TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT ck_clientes_estado
        CHECK (estado ~ '^[A-Z]{2}$')
);

CREATE TABLE public.produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    preco NUMERIC(12, 2) NOT NULL,
    estoque INTEGER NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT ck_produtos_preco
        CHECK (preco >= 0),

    CONSTRAINT ck_produtos_estoque
        CHECK (estoque >= 0)
);

CREATE TABLE public.pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    data_pedido TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    valor_total NUMERIC(14, 2) NOT NULL,

    CONSTRAINT fk_pedidos_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES public.clientes (id),

    CONSTRAINT ck_pedidos_status
        CHECK (
            status IN (
                'pendente',
                'pago',
                'enviado',
                'entregue',
                'cancelado'
            )
        ),

    CONSTRAINT ck_pedidos_valor_total
        CHECK (valor_total >= 0)
);

CREATE TABLE public.itens_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    valor_unitario NUMERIC(12, 2) NOT NULL,

    CONSTRAINT fk_itens_pedido_pedido
        FOREIGN KEY (pedido_id)
        REFERENCES public.pedidos (id),

    CONSTRAINT fk_itens_pedido_produto
        FOREIGN KEY (produto_id)
        REFERENCES public.produtos (id),

    CONSTRAINT ck_itens_pedido_quantidade
        CHECK (quantidade > 0),

    CONSTRAINT ck_itens_pedido_valor_unitario
        CHECK (valor_unitario >= 0)
);

CREATE TABLE public.pagamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    data_pagamento TIMESTAMP WITHOUT TIME ZONE,
    forma_pagamento VARCHAR(20) NOT NULL,
    valor NUMERIC(14, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,

    CONSTRAINT fk_pagamentos_pedido
        FOREIGN KEY (pedido_id)
        REFERENCES public.pedidos (id),

    CONSTRAINT ck_pagamentos_forma
        CHECK (
            forma_pagamento IN (
                'pix',
                'cartao_credito',
                'cartao_debito',
                'boleto'
            )
        ),

    CONSTRAINT ck_pagamentos_valor
        CHECK (valor > 0),

    CONSTRAINT ck_pagamentos_status
        CHECK (
            status IN (
                'pendente',
                'aprovado',
                'recusado',
                'estornado'
            )
        ),

    CONSTRAINT ck_pagamentos_data
        CHECK (
            status NOT IN ('aprovado', 'estornado')
            OR data_pagamento IS NOT NULL
        )
);

COMMIT;
